/// Returns `true` if `ch` has Unicode category `So` (Symbol, Other).
pub(crate) fn is_symbol_other(ch: char) -> bool {
    let cp = ch as u32;
    SYMBOL_OTHER_RANGES
        .binary_search_by(|&(lo, hi)| {
            if cp < lo {
                std::cmp::Ordering::Greater
            } else if cp > hi {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}
