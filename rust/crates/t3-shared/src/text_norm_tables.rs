/// Primary canonical composition of `base` + `mark` (`UAX #15`), including Hangul LV/LVT Jamo.
#[must_use]
pub(crate) fn compose_pair(base: char, mark: char) -> Option<char> {
    const HANGUL_S_BASE: u32 = 0xAC00;
    const HANGUL_L_BASE: u32 = 0x1100;
    const HANGUL_V_BASE: u32 = 0x1161;
    const HANGUL_T_BASE: u32 = 0x11A7;
    const HANGUL_L_COUNT: u32 = 19;
    const HANGUL_V_COUNT: u32 = 21;
    const HANGUL_T_COUNT: u32 = 28;
    const HANGUL_N_COUNT: u32 = HANGUL_V_COUNT * HANGUL_T_COUNT;
    const HANGUL_S_COUNT: u32 = HANGUL_L_COUNT * HANGUL_N_COUNT;

    let b = base as u32;
    let m = mark as u32;

    if (HANGUL_L_BASE..HANGUL_L_BASE + HANGUL_L_COUNT).contains(&b)
        && (HANGUL_V_BASE..HANGUL_V_BASE + HANGUL_V_COUNT).contains(&m)
    {
        let s = HANGUL_S_BASE
            + (b - HANGUL_L_BASE) * HANGUL_N_COUNT
            + (m - HANGUL_V_BASE) * HANGUL_T_COUNT;
        return char::from_u32(s);
    }
    if (HANGUL_S_BASE..HANGUL_S_BASE + HANGUL_S_COUNT).contains(&b)
        && (b - HANGUL_S_BASE).is_multiple_of(HANGUL_T_COUNT)
        && (HANGUL_T_BASE + 1..HANGUL_T_BASE + HANGUL_T_COUNT).contains(&m)
    {
        return char::from_u32(b + (m - HANGUL_T_BASE));
    }

    NFC_COMPOSITION_TABLE
        .binary_search_by_key(&(base, mark), |&(lhs, rhs, _)| (lhs, rhs))
        .ok()
        .map(|idx| NFC_COMPOSITION_TABLE[idx].2)
}

