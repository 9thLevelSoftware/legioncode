pub fn apply_isolated_env(cmd: &mut Command, home_dir: &Path) {
    for key in SCRUBBED_ENV_KEYS {
        cmd.env_remove(key);
    }
    cmd.env("LOCALAPPDATA", home_dir)
        .env("USERPROFILE", home_dir)
        .env("HOME", home_dir)
        .env("XDG_CONFIG_HOME", home_dir)
        .env("LEGIONCODE_BIN_TS", NONEXISTENT_BIN_TS)
        .env("GIT_TERMINAL_PROMPT", "0")
        .env("GIT_ASKPASS", "");
}
