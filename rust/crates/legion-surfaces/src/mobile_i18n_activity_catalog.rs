pub(crate) fn activity_catalog(locale: &str) -> &'static ActivityCatalog {
    match locale {
        "de" => &ACT_DE,
        "es" => &ACT_ES,
        "fr" => &ACT_FR,
        "ja" => &ACT_JA,
        "ko" => &ACT_KO,
        "pt-BR" => &ACT_PT_BR,
        "ru" => &ACT_RU,
        "sv" => &ACT_SV,
        "zh" => &ACT_ZH,
        _ => &ACT_EN,
    }
}

