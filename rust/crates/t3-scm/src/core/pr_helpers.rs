//! Pull request merge commit message builders and check-status rollup utilities.
//!
//! Mirrors T3 Code's `mergeMessage` (including agent attribution trailer
//! removal) and `pullRequestChecks` (status rollup, severity sorting, and
//! deduplication across providers).

use std::collections::HashMap;

use t3_contracts::pull_requests::PullRequestChecksState;

/// Formats a pull request merge commit message before stripping or appending trailers.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MergeMessageInput {
    /// Pull request title used to compose the commit subject line.
    pub title: String,
    /// Optional pull request number appended as `(#<number>)`.
    pub number: Option<u64>,
    /// Optional pull request body included below a blank line.
    pub body: Option<String>,
    /// Whether to include `body` below the commit subject.
    pub include_body: bool,
    /// Whether to strip coding-agent `Co-authored-by:` / `Generated with` trailers.
    pub strip_agent_credits: bool,
    /// Explicit human co-authors to preserve/append as trailers.
    pub co_authors: Vec<String>,
}

/// Assembled merge commit message split into subject, body, and combined text.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MergeCommitMessage {
    /// First commit line.
    pub subject: String,
    /// Sanitized commit body (without subject line), if non-empty.
    pub body: Option<String>,
    /// Full normalized commit message.
    pub full_message: String,
}

/// Raw check run or commit status state reported by upstream forges.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum RawCheckState {
    /// Check passed successfully.
    Success,
    /// Check reported neutral or non-blocking informational status.
    Neutral,
    /// Check was intentionally skipped.
    Skipped,
    /// Check is queued for execution.
    Queued,
    /// Check is waiting or pending completion.
    Pending,
    /// Check is actively running.
    InProgress,
    /// Check failed.
    Failure,
    /// Check errored due to infrastructure or script failure.
    Error,
    /// Check timed out.
    TimedOut,
    /// Check was cancelled before finishing.
    Cancelled,
    /// Check completed in an outdated/stale state.
    Stale,
}

impl RawCheckState {
    /// Maps raw check states into a coarse sort rank (`0` = failing, `1` = pending, `2` = passing).
    #[must_use]
    pub const fn severity_rank(self) -> u8 {
        match self {
            Self::Failure | Self::Error | Self::TimedOut | Self::Cancelled => 0,
            Self::Queued | Self::Pending | Self::InProgress | Self::Stale => 1,
            Self::Success | Self::Neutral | Self::Skipped => 2,
        }
    }

    /// Parses a forge status or conclusion string case-insensitively.
    #[must_use]
    pub fn from_forge_str(raw: &str) -> Self {
        match raw.trim().to_ascii_lowercase().as_str() {
            "success" | "succeeded" | "passed" | "pass" | "completed" => Self::Success,
            "neutral" => Self::Neutral,
            "skipped" => Self::Skipped,
            "queued" | "waiting" => Self::Queued,
            "in_progress" | "inprogress" | "running" => Self::InProgress,
            "failure" | "failed" | "fail" | "not_applicable" | "action_required" => Self::Failure,
            "error" | "errored" => Self::Error,
            "timed_out" | "timeout" => Self::TimedOut,
            "cancelled" | "canceled" => Self::Cancelled,
            "stale" => Self::Stale,
            _ => Self::Pending,
        }
    }
}

/// Normalized pull request check item used across providers.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CheckEntry {
    /// Check name or context key.
    pub name: String,
    /// Optional sub-context or provider qualifier.
    pub context: Option<String>,
    /// Normalized check outcome/progress state.
    pub state: RawCheckState,
    /// Whether branch protection or policy marks this check required.
    pub required: bool,
    /// Optional `ISO-8601` update timestamp used for deduplicating repeated runs.
    pub updated_at: Option<String>,
    /// Optional details URL.
    pub details_url: Option<String>,
}

const AGENT_CREDIT_MARKERS: &[&str] = &[
    "noreply@anthropic.com",
    "noreply@openai.com",
    "claude@",
    "codex@",
    "cursoragent@",
    "copilot@",
    "t3code",
    "t3 code",
    "generated with",
    "generated by claude",
    "generated by codex",
    "generated by cursor",
    "generated by opencode",
    "claude code",
    "openai codex",
    "antigravity",
];

/// Strips automated coding-agent attribution trailers (`Co-authored-by`, `Generated with`)
/// while leaving ordinary commit prose and human trailers intact.
///
/// ```
/// use t3_scm::core::pr_helpers::remove_agent_credits;
///
/// let input = "Fix bug\n\nCo-authored-by: Claude <noreply@anthropic.com>\nCo-authored-by: Alice <alice@example.com>";
/// let cleaned = remove_agent_credits(input);
/// assert_eq!(cleaned, "Fix bug\n\nCo-authored-by: Alice <alice@example.com>");
/// ```
#[must_use]
pub fn remove_agent_credits(text: &str) -> String {
    let mut kept: Vec<&str> = Vec::new();
    for line in text.lines() {
        if is_agent_credit_line(line) {
            continue;
        }
        kept.push(line.trim_end_matches('\r'));
    }

    // Collapse trailing blank lines and avoid runs of >2 consecutive newlines.
    let mut collapsed: Vec<&str> = Vec::with_capacity(kept.len());
    let mut prev_blank = false;
    for line in kept {
        let blank = line.trim().is_empty();
        if blank && (collapsed.is_empty() || prev_blank) {
            continue;
        }
        collapsed.push(line);
        prev_blank = blank;
    }
    while collapsed.last().is_some_and(|l| l.trim().is_empty()) {
        collapsed.pop();
    }
    collapsed.join("\n")
}

fn is_agent_credit_line(line: &str) -> bool {
    let lower = line.trim().to_ascii_lowercase();
    if lower.is_empty() {
        return false;
    }
    let is_trailer = lower.starts_with("co-authored-by:")
        || lower.starts_with("signed-off-by:")
        || lower.starts_with("generated with")
        || lower.starts_with("generated-by:")
        || lower.contains("noreply@anthropic.com")
        || lower.contains("noreply@openai.com");
    if !is_trailer {
        return false;
    }
    AGENT_CREDIT_MARKERS.iter().any(|m| lower.contains(m))
}

/// Builds a normalized merge commit message from pull request metadata.
#[must_use]
pub fn build_merge_commit_message(input: &MergeMessageInput) -> MergeCommitMessage {
    let base_title = input.title.split_whitespace().collect::<Vec<_>>().join(" ");
    let subject = match input.number {
        Some(num) if !base_title.ends_with(&format!("(#{num})")) => {
            format!("{base_title} (#{num})")
        }
        _ => base_title,
    };

    let mut sections: Vec<String> = Vec::new();
    if input.include_body
        && let Some(raw_body) = input.body.as_deref()
    {
        let processed = if input.strip_agent_credits {
            remove_agent_credits(raw_body)
        } else {
            raw_body.trim().to_owned()
        };
        if !processed.is_empty() {
            sections.push(processed);
        }
    }

    if !input.co_authors.is_empty() {
        let mut trailers = Vec::new();
        for author in &input.co_authors {
            let trimmed = author.trim();
            if trimmed.is_empty() {
                continue;
            }
            if trimmed.to_ascii_lowercase().starts_with("co-authored-by:") {
                trailers.push(trimmed.to_owned());
            } else {
                trailers.push(format!("Co-authored-by: {trimmed}"));
            }
        }
        if !trailers.is_empty() {
            sections.push(trailers.join("\n"));
        }
    }

    let body = if sections.is_empty() {
        None
    } else {
        Some(sections.join("\n\n"))
    };
    let full_message = match &body {
        Some(b) => format!("{subject}\n\n{b}"),
        None => subject.clone(),
    };

    MergeCommitMessage {
        subject,
        body,
        full_message,
    }
}

/// Computes the aggregate [`PullRequestChecksState`] across normalized checks.
///
/// Precedence: any failing check yields [`PullRequestChecksState::Failing`];
/// otherwise any pending/running check yields [`PullRequestChecksState::Pending`];
/// empty or all-passing/neutral/skipped yields [`PullRequestChecksState::Passing`].
///
/// ```
/// use t3_contracts::pull_requests::PullRequestChecksState;
/// use t3_scm::core::pr_helpers::{rollup_check_statuses, CheckEntry, RawCheckState};
///
/// let checks = vec![
///     CheckEntry {
///         name: "lint".into(),
///         context: None,
///         state: RawCheckState::Success,
///         required: true,
///         updated_at: None,
///         details_url: None,
///     },
///     CheckEntry {
///         name: "test".into(),
///         context: None,
///         state: RawCheckState::InProgress,
///         required: true,
///         updated_at: None,
///         details_url: None,
///     },
/// ];
/// assert_eq!(rollup_check_statuses(&checks), PullRequestChecksState::Pending);
/// ```
#[must_use]
pub fn rollup_check_statuses(checks: &[CheckEntry]) -> PullRequestChecksState {
    let mut has_pending = false;
    for check in checks {
        match check.state.severity_rank() {
            0 => return PullRequestChecksState::Failing,
            1 => has_pending = true,
            _ => {}
        }
    }
    if has_pending {
        PullRequestChecksState::Pending
    } else {
        PullRequestChecksState::Passing
    }
}

/// Sorts checks in place by severity (`Failure` < `Pending` < `Success`),
/// then `required` first, then case-insensitive name ascending.
pub fn sort_checks(checks: &mut [CheckEntry]) {
    checks.sort_by(|a, b| {
        a.state
            .severity_rank()
            .cmp(&b.state.severity_rank())
            .then_with(|| b.required.cmp(&a.required))
            .then_with(|| {
                a.name
                    .to_ascii_lowercase()
                    .cmp(&b.name.to_ascii_lowercase())
            })
            .then_with(|| a.context.cmp(&b.context))
    });
}

/// Deduplicates check entries by normalized `(name, context)`, keeping the newest entry
/// by `updated_at` timestamp (or preferring required/more severe entries when timestamps tie).
#[must_use]
pub fn dedupe_checks(checks: Vec<CheckEntry>) -> Vec<CheckEntry> {
    let mut by_key: HashMap<(String, String), CheckEntry> = HashMap::new();
    for entry in checks {
        let key = (
            entry.name.trim().to_ascii_lowercase(),
            entry
                .context
                .as_deref()
                .unwrap_or("")
                .trim()
                .to_ascii_lowercase(),
        );
        match by_key.get_mut(&key) {
            Some(existing) if !should_replace_check(existing, &entry) => {}
            Some(existing) => *existing = entry,
            None => {
                by_key.insert(key, entry);
            }
        }
    }
    let mut out: Vec<CheckEntry> = by_key.into_values().collect();
    sort_checks(&mut out);
    out
}

fn should_replace_check(existing: &CheckEntry, candidate: &CheckEntry) -> bool {
    match (&existing.updated_at, &candidate.updated_at) {
        (Some(old_ts), Some(new_ts)) if new_ts != old_ts => new_ts > old_ts,
        (None, Some(_)) => true,
        (Some(_), None) => false,
        _ => {
            (candidate.required && !existing.required)
                || candidate.state.severity_rank() < existing.state.severity_rank()
        }
    }
}
