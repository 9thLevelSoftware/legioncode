pub(crate) fn is_hdl_keyword(lang: HdlLanguage, word: &str) -> bool {
    match lang {
        HdlLanguage::Verilog => VERILOG_KEYWORDS.contains(&word),
        HdlLanguage::SystemVerilog => {
            VERILOG_KEYWORDS.contains(&word) || SV_EXTRA_KEYWORDS.contains(&word)
        }
        HdlLanguage::Vhdl => VHDL_KEYWORDS.iter().any(|kw| kw.eq_ignore_ascii_case(word)),
    }
}
