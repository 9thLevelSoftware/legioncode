/// Resolves localized copy for the active [`LocaleState`] without falling back to English
/// for any supported locale.
#[must_use]
pub fn feature_copy(locale: &LocaleState) -> WebFeatureCopy {
    catalog_for(&locale.catalog_locale)
}

const fn catalog_for(code: &str) -> WebFeatureCopy {
    match code.as_bytes() {
        b"de" | b"es" | b"fr" => catalog_west_eu(code),
        b"pt-BR" | b"ru" | b"sv" => catalog_other_eu(code),
        _ => catalog_global(code),
    }
}

